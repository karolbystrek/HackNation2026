// Copies the knowledge/ records the guide references into app/lib/guide/knowledge.json.
// The app (and its Docker build context) only sees app/, so it reads this trimmed snapshot.
// Run from the repo root after changing knowledge/ or guide.json: node scripts/guide-knowledge.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (path) => JSON.parse(readFileSync(root + path, "utf8"));
const OUT = "app/lib/guide/knowledge.json";

export function buildSnapshot() {
  const guide = read("app/lib/guide/guide.json");
  const load = (name) => new Map(read(`knowledge/${name}.json`).records.map((r) => [r.id, r]));
  const kb = Object.fromEntries(["benefits", "scenarios", "forms", "documents", "leave_requests", "risks", "support_orgs", "glossary"].map((n) => [n, load(n)]));
  const pick = (collection, ids, fields) => Object.fromEntries([...ids].sort().map((id) => {
    const record = kb[collection].get(id);
    if (!record) throw new Error(`${collection}: missing ${id}`);
    if (record.status !== "current") throw new Error(`${collection}: ${id} is ${record.status}`);
    return [id, Object.fromEntries(fields.filter((f) => record[f] !== undefined).map((f) => [f, record[f]]))];
  }));

  const ids = { benefits: new Set(), scenarios: new Set(), forms: new Set(), documents: new Set(), leave_requests: new Set(), risks: new Set() };
  // Terms marked as [text](term.id) in question texts get a popup with their glossary definition.
  const texts = guide.questions.flatMap((q) => [q.label, q.hint, ...(q.options ?? []).flatMap((o) => [o.label, o.hint])]);
  const terms = new Set(texts.flatMap((t) => [...(t ?? "").matchAll(/\]\((term\.[a-z0-9_]+)\)/g)].map((m) => m[1])));
  for (const t of guide.topics) {
    t.benefitIds?.forEach((id) => ids.benefits.add(id));
    t.scenarios?.forEach((s) => ids.scenarios.add(s.id));
    t.riskIds?.forEach((r) => ids.risks.add(typeof r === "string" ? r : r.id));
  }
  for (const id of ids.scenarios) {
    const scenario = kb.scenarios.get(id);
    if (!scenario) throw new Error(`scenarios: missing ${id}`);
    scenario.risk_ids?.forEach((r) => ids.risks.add(r));
    for (const step of scenario.steps) {
      step.form_ids?.forEach((f) => ids.forms.add(f));
      step.document_ids?.forEach((d) => ids.documents.add(d));
      step.leave_request_ids?.forEach((l) => ids.leave_requests.add(l));
    }
  }
  const situations = new Set(guide.topics.flatMap((t) => t.support ?? []).map((s) => s.situation));
  const orgs = [...kb.support_orgs.values()].filter((o) => o.status === "current" && o.situations.some((s) => situations.has(s))).map((o) => o.id);
  const actor = read("knowledge/enums.json").records.find((r) => r.id === "actor").values;

  const scenarios = pick("scenarios", ids.scenarios, ["title_pl", "summary_pl", "steps", "risk_ids"]);
  for (const s of Object.values(scenarios)) {
    s.steps = s.steps.map(({ order, actor, action_pl, recipient, form_ids, document_ids, leave_request_ids }) => ({ order, actor, action_pl, recipient, form_ids, document_ids, leave_request_ids }));
  }
  return {
    $comment: "Generated by scripts/guide-knowledge.mjs from knowledge/. Do not edit by hand.",
    actors: Object.fromEntries(actor.map((a) => [a.value, a.label_pl])),
    benefits: pick("benefits", ids.benefits, ["title_pl", "summary_pl"]),
    scenarios,
    forms: pick("forms", ids.forms, ["symbol", "title_pl", "page_url"]),
    documents: pick("documents", ids.documents, ["title_pl", "how_to_obtain_pl"]),
    leave_requests: pick("leave_requests", ids.leave_requests, ["code", "title_pl"]),
    risks: pick("risks", ids.risks, ["title_pl", "consequence_pl", "prevention_pl"]),
    support_orgs: pick("support_orgs", orgs, ["title_pl", "summary_pl", "website", "phones", "situations"]),
    glossary: pick("glossary", terms, ["term_pl", "definition_pl"]),
  };
}

export const serialize = (snapshot) => JSON.stringify(snapshot, null, 2) + "\n";

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = serialize(buildSnapshot());
  if (process.argv.includes("--check")) {
    const same = readFileSync(root + OUT, "utf8") === text;
    console.log(same ? "snapshot up to date" : `stale: run node scripts/guide-knowledge.mjs`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(root + OUT, text);
  console.log(`wrote ${OUT}`);
}
